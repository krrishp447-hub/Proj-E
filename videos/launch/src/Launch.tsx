import { AbsoluteFill, Audio, Sequence, interpolate, staticFile } from "remotion";
import { Field } from "./Field";
import { DataNote, Fake, Hook, Outro, Proof, Rows, SearchBar, Wordmark } from "./Scenes";
import { C } from "./theme";
import { DURATION, T } from "./timing";

export type LaunchProps = { url: string };

export function Launch({ url }: LaunchProps) {
  return (
    <AbsoluteFill style={{ background: C.ink }}>
      <Field />
      {/* soft vignette keeps the eye centred and the edges quiet */}
      <AbsoluteFill style={{ background: "radial-gradient(75% 70% at 50% 48%, transparent 55%, rgba(6,7,6,.85) 100%)" }} />

      <Sequence from={0} durationInFrames={T.fake} name="Hook"><Hook /></Sequence>
      <Sequence from={T.fake} durationInFrames={T.search - T.fake} name="Fake"><Fake /></Sequence>
      <Sequence from={T.wordmark} durationInFrames={T.outro + 20 - T.wordmark} name="Wordmark"><Wordmark /></Sequence>
      <Sequence from={T.search} durationInFrames={T.proof + 20 - T.search} name="Search"><SearchBar /></Sequence>
      <Sequence from={T.rows} durationInFrames={T.outro + 20 - T.rows} name="Rows"><Rows /></Sequence>
      <Sequence from={T.rows} durationInFrames={T.outro + 20 - T.rows} name="Data note"><DataNote /></Sequence>
      <Sequence from={T.proof} durationInFrames={T.outro + 20 - T.proof} name="Proof"><Proof /></Sequence>
      <Sequence from={T.outro} durationInFrames={DURATION - T.outro} name="Outro"><Outro url={url} /></Sequence>

      {/* Placeholder score generated by scripts/make-music.ts — replace public/music.wav with the licensed track. */}
      <Audio
        src={staticFile("music.wav")}
        volume={(f) => interpolate(f, [0, 6, T.audioFadeEnd - 40, T.audioFadeEnd], [0, 1, 1, 0], { extrapolateLeft: "clamp", extrapolateRight: "clamp" })}
      />
    </AbsoluteFill>
  );
}
